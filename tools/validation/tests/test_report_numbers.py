"""Phase 05g scope 2: the numbers in report-phase05.md that used to be hand-typed are computed from the
committed data (bras_reduction.json, bras_geometry.json) or cited to bras_mapping.md §1. Pins them, so the
report cannot go stale against the data without this test failing. No BRAS cache or render_cli needed."""

import json
import pathlib
import re

import pytest

from tools.validation import report

REPO = pathlib.Path(__file__).resolve().parents[3]


def test_seating_s_is_read_from_the_reduction():
    s = report.seating_s(report.load_reduction(), ["CR3", "CR4"])
    assert [round(x, 2) for x in s["CR3"]] == [0.43, 0.60, 0.87]
    assert [round(x, 2) for x in s["CR4"]] == [0.43, 0.60, 0.85]
    assert report.seating_s_text(report.load_reduction(), ["CR3", "CR4"]) == "0.43 / 0.60 / 0.85–0.87"


def test_seating_s_agrees_with_the_bras_mapping_classification_table():
    # bras_mapping.md §5 per-material table (generated by make_bras_scenes.py from the same reduction)
    text = (REPO / "docs" / "validation" / "bras_mapping.md").read_text(encoding="utf-8")
    row = re.search(r"\| CR3 \| seating \|[^\n]*", text).group(0)
    assert "0.43 / 0.60 / 0.87" in row


def test_volume_ratios_are_computed_from_the_model_volumes():
    v = report.model_volumes()
    assert v == {"CR2": 146.1, "CR3": 3330.6, "CR4": 8656.5}  # _descr/mat_CRx.txt, bras_mapping.md §1 table
    r = report.volume_ratios_pct(["CR2", "CR3", "CR4"], v)
    assert r["CR2"] == pytest.approx(0.7586, abs=1e-3)
    assert r["CR3"] == pytest.approx(41.728, abs=1e-2)
    assert r["CR4"] == pytest.approx(0.0751, abs=1e-3)
    p = report.volume_paragraph(["CR2", "CR3", "CR4"])
    assert "+0.76 % in CR2 (146.1 vs 145 m³" in p
    assert "+41.73 % in CR3 (3 330.6 vs 2 350 m³" in p
    assert "+0.08 % in CR4 (8 656.5 vs 8 650 m³" in p


def test_sheet_volumes_are_the_ones_bras_mapping_cites():
    text = (REPO / "docs" / "validation" / "bras_mapping.md").read_text(encoding="utf-8")
    assert "give CR2 145 m³,\nCR3 2 350 m³ \"excluding the attic\", CR4 8 650 m³" in text
    assert report.BRAS_SHEET_VOLUME_M3 == {"CR2": 145.0, "CR3": 2350.0, "CR4": 8650.0}


def test_fit_figures_are_cited_not_typed():
    """The fitted-α T20 reproduction figures need the BRAS measurements; the report cites bras_mapping.md §1,
    which states them (CR2 ≤ 0.45 %, CR3 ≤ 0.23 %, CR4 ≤ 0.29 % with the model volumes)."""
    p = report.volume_paragraph(["CR2", "CR3", "CR4"])
    assert "bras_mapping.md §1" in p and "0.45" not in p and "0.29" not in p
    text = (REPO / "docs" / "validation" / "bras_mapping.md").read_text(encoding="utf-8")
    for fig in ("V = 146.1: +0.11 % / 0.45 %", "V = 3 330.6: +0.02 % / 0.23 %", "V = 8 656.5: +0.06 % / 0.29 %"):
        assert fig in text


def test_committed_report_matches_the_committed_results():
    """Regenerating the report from phase05_results.json reproduces the committed file (no hand edits)."""
    res = json.loads((REPO / "tools" / "validation" / "data" / "phase05_results.json").read_text(encoding="utf-8"))
    out = []

    class _P:
        def write_text(self, t, encoding=None):
            out.append(t)

    report.write(res, _P())
    assert out[0] == (REPO / "docs" / "validation" / "report-phase05.md").read_text(encoding="utf-8")


def test_b12_paragraph_is_the_recorded_outcome():
    text = (REPO / "docs" / "validation" / "report-phase05.md").read_text(encoding="utf-8")
    assert "Open plan question (/fix-plan)" not in text
    res = json.loads((REPO / "tools" / "validation" / "data" / "phase05_results.json").read_text(encoding="utf-8"))
    assert report.b12_recorded_outcome(res) in text
    assert "accepted by Maisara 2026-11-07" in report.B12_RECORDED_OUTCOME



def test_b12_room_band_count_is_computed():
    """'Eyring under-predicts T in 8 of 9 room-bands' (BUILD_PLAN §5 B12, ledger F5f-6) comes from the results."""
    res = json.loads((REPO / "tools" / "validation" / "data" / "phase05_results.json").read_text(encoding="utf-8"))
    assert report.eyring_under_prediction(res) == (8, 9, ["CR2", "CR3", "CR4"])
    assert "under-predicts T in 8 of 9 room-bands (CR2, CR3, CR4 at 500 Hz–2 kHz" in report.b12_recorded_outcome(res)
