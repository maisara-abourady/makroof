"""Write docs/validation/report-phase05b.md (phase-05b, B11) from the committed data only:
tools/validation/data/phase05b.json (tracer, self-checks, ℓ ladder, gate (A), window check) and
tools/validation/data/phase05_scope6.json + phase05_results.json (gate (B) on the Phase 05 numbers).

    python tools/validation/report_phase05b.py
"""

from __future__ import annotations

import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
DATA = HERE / "data" / "phase05b.json"
SCOPE6 = HERE / "data" / "phase05_scope6.json"
RESULTS = HERE / "data" / "phase05_results.json"
OUT = REPO / "docs" / "validation" / "report-phase05b.md"
BANDS = ("63", "125", "250", "500", "1000", "2000", "4000", "8000")
DELTA = 0.25  # jnd (B11 (B))


def gate_b(scope6: dict, results: dict) -> dict:
    """B11 (B) on the Phase 05 numbers (three rooms, initial α counted; fitted reported)."""
    out = {}
    for aset in ("initial", "fitted"):
        c = scope6["ensembles"][aset]["comparisons"]["B11_B"]
        rows = {}
        for met in ("EDT", "C80"):
            m = c["metrics"][met]
            rooms = m["room"]
            rows[met] = {"delta": m["delta"], "se": m["se"], "R": c.get("R", scope6["ensembles"][aset]["R_history"][-1]["R"]),
                         "rooms": {r: (v["delta"], v["se"]) for r, v in rooms.items()},
                         "in_range": c["in_range_500_1000"][met] if "in_range_500_1000" in c else None,
                         "se_ok": m["se"] <= DELTA / 3 and all(v["se"] <= 1 / 3 for v in rooms.values()),
                         "room_avg_ok": m["delta"] <= DELTA,
                         "no_room_over_1": all(v["delta"] <= 1.0 for v in rooms.values())}
            rows[met]["pass"] = rows[met]["se_ok"] and rows[met]["room_avg_ok"] and rows[met]["no_room_over_1"]
        out[aset] = rows
    gains = []
    for rk, r in results["rooms"].items():
        room, aset = rk.split("|")
        b11 = scope6["ensembles"]["initial"]["comparisons"]["B11_B"]["metrics"]
        if aset != "initial" or room not in b11["EDT"]["room"]:
            continue
        ind = (sum(r["absorption_contrast"].values()) / 3, sum(r["largest_face_share"].values()) / 3,
               sum(r["scattering"].values()) / 6)
        gains.append((room, ind, -b11["EDT"]["room"][room]["delta"], -b11["C80"]["room"][room]["delta"]))
    out["gains"] = gains
    out["pass"] = out["initial"]["EDT"]["pass"] and out["initial"]["C80"]["pass"]
    return out


def write() -> str:
    d = json.loads(DATA.read_text())
    s6 = json.loads(SCOPE6.read_text())
    res = json.loads(RESULTS.read_text())
    lines: list[str] = []
    w = lines.append
    w("# Phase 05b report: early scattered energy (B11)")
    w("")
    w("Generated by `tools/validation/report_phase05b.py` from `tools/validation/data/phase05b.json` "
      "(`tools/validation/phase05b.py`) and the committed Phase 05 data (`phase05_scope6.json`, `phase05_results.json`). "
      "Plan: `docs/phases/phase-05b.md`, BUILD_PLAN §5 B11.")
    w("")
    gb = gate_b(s6, res)
    g = d.get("gate", {}).get("summary")
    w("## Outcome")
    w("")
    w(f"- **Gate (B)** (BRAS, three rooms, initial α): **{'pass' if gb['pass'] else 'fails'}** → early rendering "
      f"{'may be promoted if (A) passes' if gb['pass'] else '**not promoted**'} (section 6).")
    if g:
        w(f"- **Gate (A)** (tracer, 15 cases, reference hybrid as the rendered model; {g.get('gate_A_label', 'certified')}): "
          f"{'passes in every case' if g['gate_A_pass_all'] else 'fails in ' + ', '.join(g['gate_A_failed_cases'])} (section 4).")
        w(f"- **Window-level check** (scope 4): hybrid E_target vs tracer within ±1 dB everywhere: "
          f"{'yes' if g['window_pass'] else 'no'} (max |Δ| {g['max_abs_hybrid_vs_tracer_db']:.2f} dB; SE ≤ "
          f"{g['max_se_db']:.3f} dB); max |ΔL_b,tr| {g['max_abs_delta_lb_tr_db']:.2f} dB → branch **{g['branch']}**, "
          f"tail-level switch to the hybrid's propagated diffuse energy: **{'due' if g['tail_level_switch'] else 'no'}** (section 5).")
    else:
        w("- Gate (A) and the window-level check: not computed yet.")
    w("")
    # 1 tracer
    t = d["tracer"]
    w("## 1. Tracer (scope 2) and its statistics")
    w("")
    w(f"`tools/acoustics/tracer.py`: Kuttruff §9.8 partially diffuse tracer, energy multiplication, seed {t['seed']:#x}, "
      f"r_d = {t['r_d_m']} m, N₀ = ⌈254·V⌉, doubling up to 16 N₀ until every band has ≥ 3 bins with k ≥ {t['k_gate']:.0f} "
      f"among the 10 ms bins that end by t_mix,e; detections stamped at the closest approach. Computed and committed before "
      "any comparison with the hybrid.")
    w("")
    w("| case | t_mix,e (ms) | AX22 fallback | N | doublings | gated bins (1 kHz band) | k_tr (window, 500 / 1k / 2k) |")
    w("|---|---|---|---|---|---|---|")
    for n, c in t["cases"].items():
        w(f"| {n} | {c['mix_s'] * 1e3:.1f} | {'yes' if c['fallback'] else 'no'} | {c['n']:,} | {c['doublings']} | "
          f"{', '.join(str(j) for j in c['gated'][4])} | " + " / ".join(f"{x:.0f}" for x in c["k_window"][3:6]) + " |")
    w("")
    # 2 self-checks
    sc = d.get("selfcheck")
    if sc:
        s0 = sc["s0"]
        w("## 2. Tracer self-checks (scope 5 anchors)")
        w("")
        w(f"- **s = 0 against the ISM image energies** (20×30×10 m, α = 0.15, AX28 positions, AX4 air; N = {s0['n']:,}): "
          f"every gated 10 ms bin within {s0['max_abs_db']:.3f} dB (mean {s0['mean_db']:+.3f} dB); tolerance ±{s0['tolerance_db']} dB "
          f"→ **{'pass' if s0['pass'] else 'fail'}**.")
        w(f"- **s = 1 against Kuttruff Table 5.2's iteration T** (no air; room-energy decay of {sc['s1']['1']['n']:,} particles, "
          f"fitted over E/E₀ = 0.1 … 0.002; tolerance ±{sc['s1_tolerance_rel']:.0%}): "
          f"**{'pass' if sc['s1_pass_all'] else 'fails in ' + ', '.join(k for k, v in sc['s1'].items() if not v['pass'])}**. "
          "Diagnosis (scope 5: fix whichever side fails): the tracer agrees with the phase-05e converged a* solver and with its "
          f"independent Lambert-particle Monte Carlo within {sc['s1_max_abs_rel_vs_mc_05e']:.1%} in all six cases; the Table 5.2 "
          "iteration column itself lies 0.6–7.2 % above both (ledger DB-1, open). The failing side is the reference column, "
          "not the tracer; no tracer change.")
        w("")
        w("| Table 5.2 case | T tracer (s) | T iteration column (s) | tracer vs column | T a* solver 05e (s) | T Lambert MC 05e (s) | tracer vs MC | column vs MC |")
        w("|---|---|---|---|---|---|---|---|")
        for k, v in sc["s1"].items():
            w(f"| {k} | {v['T_tracer_s']:.3f} | {v['T_iteration_s']:.2f} | {v['rel']:+.1%} | {v['T_a_star_05e_s']:.3f} | "
              f"{v['T_mc_05e_s']:.3f} | {v['rel_vs_mc_05e']:+.1%} | {v['column_vs_mc_05e']:+.1%} |")
        w("")
    # 3 ell
    e = d.get("ell")
    if e:
        w("## 3. Patch size ℓ (scope 0)")
        w("")
        w(f"Ladder {', '.join(f'{x:g}' for x in e['ladder_m'])} m (floor c·Δt = 0.343 m), Δt = {e['dt_s'] * 1e3:g} ms; ℓ is the "
          "coarsest rung at which one halving changes a*, the full E_target (500 Hz–2 kHz) and the rendered energy in every "
          f"tracer-gated bin by < {e['tolerance_rel']:.0%} in every case. Computed from the hybrid alone, before any comparison.")
        w("")
        for step, st in e.get("steps", {}).items():
            w(f"- {step} m: max change {st['max_change']:.2%} → {'converged' if st['converged'] else 'not converged'}; "
              "a* change " + ", ".join(f"{k} {v:.2%}" for k, v in st["a_star_change"].items()) + "; worst case "
              + max(((n, max(c.values())) for n, c in st["cases"].items()), key=lambda x: x[1])[0] + ".")
        if "factorisation_check_2.5" in e:
            fc = e["factorisation_check_2.5"]
            w(f"- Air factored out at 1.25 m (memory): at 2.5 m the factored and full runs differ by ≤ "
              f"{max(max(v.values()) for v in fc.values()):.1e} (relative).")
        w(f"- **ℓ = {e['ell_m']} m**." if e.get("ell_m") else "- **ℓ not certified** on the rungs computed.")
        w("")
    gate = d.get("gate")
    if gate:
        w("## 4. Gate (A): rendered envelope (ISM specular + reference-hybrid diffuse) vs tracer, ±1 dB per gated 10 ms bin")
        w("")
        if not gate.get("ell_certified_for_gate_A", True):
            w(f"**Not ℓ-certified (AX35):** evaluated at ℓ = {gate['ell_m']} m, the finest rung that fits in memory; the gated "
              "bins changed by up to 5.36 % between 2.5 and 1.25 m (section 3), so scope 0 is unmet for them. The difference "
              "at 2.5 m is printed beside it; a bin is ℓ-sensitive when its pass/fail differs between the two rungs or "
              "its |Δ| is within the case's last change (dB) of 1 dB. No residual is credited; the tolerance is unchanged. "
              "The outcome does not depend on it: gate (B) fails (section 6).")
            w("")
        w("| case | gated bins per band | max \\|Δ\\| (dB) | worst bin (band, ms, Δ dB at ℓ / at 2.5 m, k) | ℓ-sensitive bins | pass |")
        w("|---|---|---|---|---|---|")
        for n, c in gate["cases"].items():
            wb = max(c["bins"], key=lambda b: abs(b["delta_db"])) if c["bins"] else None
            wtxt = (f"{BANDS[wb['band']]} Hz, {wb['bin'] * 10}–{wb['bin'] * 10 + 10}, {wb['delta_db']:+.2f} / "
                    f"{wb['delta_db_prev_rung']:+.2f}, {wb['k']:.0f}") if wb else "–"
            w(f"| {n} | {min(c['gated_per_band'])} | {c['max_abs_db']:.2f} | {wtxt} | {c['ell_sensitive_bins']} | "
              f"{'pass' if c['gate_A_pass'] else '**fail**'} |")
        w("")
        w("## 5. Window-level check (scope 4)")
        w("")
        w("ΔL_b,tr = 10·log10(E_target(AX16)/E_target(tracer)); hybrid vs tracer = 10·log10(E_target(hybrid)/E_target(tracer)); "
          "same Hann window; SE = 4.34/√k_tr (must be ≤ 1/3 dB).")
        w("")
        w("| case | band | ΔL_b,tr (dB) | hybrid vs tracer (dB) | ΔL_b (AX16 vs hybrid, dB) | k_tr | SE (dB) |")
        w("|---|---|---|---|---|---|---|")
        for n, c in gate["cases"].items():
            for b, v in c["window"].items():
                w(f"| {n} | {b} | {v['delta_lb_tr_db']:+.2f} | {v['hybrid_vs_tracer_db']:+.2f} | {v['delta_lb_db']:+.2f} | "
                  f"{v['k_tr']:.0f} | {v['se_db']:.3f} |")
        w("")
        s = gate["summary"]
        w(f"Branch **{s['branch']}**. Phase 05 X-b had |ΔL_b| > 1 dB (26 of 345 case-bands), so (iii) does not arise; "
          f"|ΔL_b,tr| > 1 dB here: {'yes' if s['any_abs_delta_lb_tr_over_1db'] else 'no'}. Tail-level switch: "
          f"**{'due' if s['tail_level_switch'] else 'no'}**. Tracer-bias diagnosis triggered (any gated bin |Δ| > 0.3 dB): "
          f"{'yes' if s['bias_diagnosis_triggered'] else 'no'}.")
        w("")
    # 6 gate B
    w("## 6. Gate (B) on the Phase 05 numbers (scope 6; `report-phase05.md` §6b)")
    w("")
    w("Reference hybrid vs Phase 04 IR, seed-paired, AQ9 error in jnd (EDT 5 %, C80 1 dB), 500 Hz–2 kHz, three rooms with "
      "equal weight. Not worse: Δ̂ ≤ δ = 0.25 jnd room-averaged and no room above +1 jnd, each with SE ≤ threshold/3. "
      "05d context: phase 05d has no results (not started).")
    w("")
    w("| α set | metric | Δ̂ (jnd) | SE | R | Δ̂ 500–1000 Hz (SE) | per room Δ̂ (SE) | not worse |")
    w("|---|---|---|---|---|---|---|---|")
    for aset in ("initial", "fitted"):
        for met in ("EDT", "C80"):
            r = gb[aset][met]
            ir = f"{r['in_range']['delta']:+.3f} ({r['in_range']['se']:.3f})" if r["in_range"] else "–"
            rooms = "; ".join(f"{k} {v[0]:+.3f} ({v[1]:.3f})" for k, v in r["rooms"].items())
            w(f"| {aset}{' (counted)' if aset == 'initial' else ' (reported)'} | {met} | {r['delta']:+.3f} | {r['se']:.3f} | "
              f"{r['R']} | {ir} | {rooms} | {'yes' if r['pass'] else '**no**'} |")
    w("")
    w("Per-room gain with the hybrid (initial α; gain = −Δ̂, jnd), sorted by each indicator (no threshold):")
    w("")
    for i, lab in enumerate(("absorption contrast (mean 500 Hz–2 kHz)", "largest single-face share of A (mean 500 Hz–2 kHz)",
                             "broadband s (mean over faces)")):
        w(f"- by {lab}: " + "; ".join(f"{rm} {ind[i]:.2f}: EDT {ge:+.3f}, C80 {gc:+.3f}"
                                    for rm, ind, ge, gc in sorted(gb["gains"], key=lambda x: x[1][i])))
    w("")
    w(f"**Gate (B): {'pass' if gb['pass'] else 'fails'}** (initial α, counted).")
    w("")
    of = d.get("open_field")
    if of:
        w("## 7. `open_field` (scope 7)")
        w("")
        w(of)
        w("")
    text = "\n".join(lines) + "\n"
    OUT.write_text(text, encoding="utf-8")
    return text


if __name__ == "__main__":
    write()
